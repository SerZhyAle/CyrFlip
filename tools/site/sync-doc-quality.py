"""Synchronize CyrFlip site metadata, search index and sitemap.

Run with --write after editing site pages; --check is a read-only release check.
Translation source hashes are deliberately refreshed only with --stamp-translations,
after the translated body has been reviewed against its English counterpart.
Sitemap <lastmod> follows tools/site/sitemap-lastmod.json: a page's date moves only when its content
fingerprint does (--write), so --check stays stable across commits. Help pages are never in the sitemap
(CONTEXT-HELP 0.2 item G); their search-index entries belong to tools/help/finalize.py and are carried unchanged.
Release facts (version, date, the versioned ZIP and its .sha256) are rendered into the 13 landings and the landing
JSON-LD only from tools/site/release-facts.json, which tools/site/Render-ReleaseFacts.ps1 writes from the version
release.ps1 releases; without that file the block stays empty and no version is stated. The block is outside the
content fingerprint, so a release moves neither a translation stamp nor a sitemap date.
"""
