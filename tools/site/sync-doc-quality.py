OG_LOCALE = {"en": "en_US", "ru": "ru_RU", "uk": "uk_UA", "de": "de_DE", "it": "it_IT", "es": "es_ES", "fr": "fr_FR",
             "pt": "pt_BR", "ar": "ar_SA", "hi": "hi_IN", "bn": "bn_BD", "ur": "ur_PK", "zh": "zh_CN"}


def release_facts():
    """The release the site states, or None. Everything but the version is derived from it."""
    if not RELEASE_FACTS.exists():
        return None
    version = json.loads(RELEASE_FACTS.read_text(encoding="utf-8-sig")).get("version", "")
    if not VERSION_SHAPE.match(version):
        raise SystemExit("release-facts.json: version %r is not the YY.M.D.HHmm shape" % version)
    year, month, day = (int(part) for part in version.split(".")[:3])
    tag, zip_name = "v" + version, "CyrFlip-" + version + "-windows-x64.zip"
    return {"version": version, "tag": tag, "date": datetime.date(2000 + year, month, day).isoformat(),
            "zip": RELEASE_BASE + "/download/" + tag + "/" + zip_name,
            "sha256": RELEASE_BASE + "/download/" + tag + "/" + zip_name + ".sha256",
            "notes": RELEASE_BASE + "/tag/" + tag}


def release_block(facts):
    # Language-neutral on purpose: a version, an ISO date and two file links read the same in all 13 landings.
    if facts is None:
        return FACTS_OPEN + FACTS_CLOSE
    return (FACTS_OPEN + '\n      <p class="whatfor release-facts" dir="ltr"><a href="' + facts["notes"] + '">'
            + facts["tag"] + '</a> · <time datetime="' + facts["date"] + '">' + facts["date"] + '</time> · <a href="'
            + facts["zip"] + '">ZIP</a> · <a href="' + facts["sha256"] + '">SHA-256</a></p>\n      ' + FACTS_CLOSE)


def with_release_block(text, facts):
    if FACTS_BLOCK.search(text):
        return FACTS_BLOCK.sub(lambda m: release_block(facts), text, count=1)
    # First render: the marker goes right after the download channels of the get section.
    start = text.find('<div class="channels">', text.find('id="get"'))
    end = text.find("</div>", start) if start >= 0 else -1
    if start < 0 or end < 0:
        raise SystemExit("landing without a get-section channels row: cannot place the release facts")
    end += len("</div>")
    return text[:end] + "\n      " + release_block(facts) + text[end:]


def social_image():
    # The site's own 1200x630 card once tools/IconGen has written it; the repository image until then.
    if SOCIAL_CARD.exists():
        return BASE + "assets/social-card.png", 1200, 630
    return LEGACY_IMAGE


def page(kind, locale):
    return DOCS / (kind + ".html" if locale == "en" else locale + "/" + ("index" if kind == "index" else kind) + ".html")


def url(kind, locale):
    return BASE + ("" if kind == "index" and locale == "en" else
                   locale + "/" if kind == "index" else
                   ("" if locale == "en" else locale + "/") + kind + ".html")


def body_hash(source):
    match = re.search(r"<body\b[^>]*>(.*)</body>", source, re.S | re.I)
    if match is None:
        return None
    body = match.group(1)
    # Metadata, theme script, footer layout and the release facts are outside the content fingerprint.
    body = re.split(r"<footer\b", body, maxsplit=1, flags=re.I)[0]
    body = FACTS_BLOCK.sub("", body)
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def content_hash(path):
    return body_hash(path.read_text(encoding="utf-8"))


def source_hash(kind):
    return content_hash(page(kind, "en"))


def git(*args):
    return subprocess.run(["git", "-C", str(ROOT)] + list(args), capture_output=True, text=True, encoding="utf-8",
                          errors="replace")


def first_lastmod(path):
    # A page committed as it is now dates from its last commit; an uncommitted edit dates from today.
    # The fingerprint excludes the metadata block, so a regenerated head does not count as an edit.
    relative = path.relative_to(ROOT).as_posix()
    committed = git("show", "HEAD:" + relative)
    if committed.returncode == 0:
        source = committed.stdout.replace("\r\n", "\n")
        if body_hash(source) == content_hash(path):
            date = git("log", "-1", "--format=%cs", "--", relative).stdout.strip()
            if date:
                return date
    return datetime.date.today().isoformat()


def lastmod_dates(pages, write):
    """The date each page's content last changed, kept by content fingerprint so --check is stable."""
    record = json.loads(LASTMOD.read_text(encoding="utf-8")) if LASTMOD.exists() else {}
    fresh, stale = {}, []
    for kind, locale, path in pages:
        address, digest = url(kind, locale), content_hash(path)
        entry = record.get(address)
        if entry and entry.get("sha256") == digest:
            fresh[address] = entry
        elif write:
            fresh[address] = {"sha256": digest, "lastmod": first_lastmod(path)}
        else:
            stale.append(address)
            fresh[address] = entry or {"sha256": digest, "lastmod": ""}
    return fresh, stale


def metadata(path, kind, locale, stamp):
    old = path.read_text(encoding="utf-8")
    if 'name="robots" content="noindex"' in old:
        return old
    title = html.unescape(re.search(r"<title>(.*?)</title>", old, re.S | re.I).group(1)).strip()
    title = SHORT_TITLES.get((kind, locale), title)
    if len(title) >= 60:
        title = "CyrFlip - " + title.replace("CyrFlip", "").strip(" -—")[:45].rstrip()
    description = html.unescape(re.search(r'<meta name="description" content="([^"]*)"', old, re.I).group(1))
    canonical = url(kind, locale)
    og_description_match = re.search(r'<meta property="og:description" content="([^"]*)"', old, re.I)
    og_description = html.unescape(og_description_match.group(1)) if og_description_match else description
    description = SHORT_DESCRIPTIONS.get((kind, locale), description)
    if len(description) >= 150 or description.endswith("VS Code."):
        description = og_description if len(og_description) < 160 else description[:145].rsplit(" ", 1)[0].rstrip(" ,;:") + "."
    image, image_width, image_height = social_image()
    # Every page is a WebPage that is part of the one site; a guide's article is that page's main entity.
    website = {"@type": "WebSite", "@id": SITE_ID, "url": BASE, "name": "CyrFlip"}
    page_node = {"@type": "WebPage", "@id": canonical + "#page", "headline": title, "url": canonical,
                 "description": description, "inLanguage": locale, "isPartOf": {"@id": SITE_ID}}
    if kind == "index":
        # The landing describes the product itself (canon PROMOTION.md section 3): one top-level
        # SoftwareApplication the page references by @id, its own canonical url, the durable download and install
        # addresses, price 0, no rating, and a version only from the release facts (never typed).
        page_node["about"] = {"@id": canonical + "#app"}
        help_locale = locale if locale in TRANSLATED["guide"] else "en"
        app = {"@type": "SoftwareApplication", "@id": canonical + "#app", "name": "CyrFlip",
               "operatingSystem": "Windows", "applicationCategory": "UtilitiesApplication", "url": canonical,
               "downloadUrl": RELEASES_URL, "installUrl": STORE_URL,
               "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
               "license": LICENSE_URL, "author": AUTHOR,
               "softwareHelp": {"@type": "CreativeWork", "url": url("guide", help_locale)},
               "releaseNotes": RELEASE_BASE}
        shot = SCREENSHOT.format(help_locale)
        if (DOCS / shot).exists():
            app["screenshot"] = BASE + shot
        facts = release_facts()
        if facts:
            app["softwareVersion"] = facts["version"]
            app["releaseNotes"] = facts["notes"]
        json_ld = {"@context": "https://schema.org", "@graph": [website, page_node, app]}
    else:
        page_node["about"] = {"@type": "SoftwareApplication", "name": "CyrFlip", "operatingSystem": "Windows"}
        if kind == "guide":
            page_node["mainEntity"] = {"@type": "TechArticle", "headline": title, "description": description,
                                       "inLanguage": locale, "url": canonical}
            page_node["breadcrumb"] = {"@type": "BreadcrumbList", "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": "CyrFlip", "item": url("index", locale)},
                {"@type": "ListItem", "position": 2, "name": title, "item": canonical}]}
        json_ld = {"@context": "https://schema.org", "@graph": [website, page_node]}
    block = ["  <!-- doc-quality metadata: generated by tools/site/sync-doc-quality.py -->",
             '  <meta charset="utf-8">',
             "  <title>" + html.escape(title) + "</title>",
             '  <meta name="description" content="' + html.escape(description, quote=True) + '">',
             '  <link rel="canonical" href="' + canonical + '">',
             '  <meta property="og:title" content="' + html.escape(title, quote=True) + '">',
             '  <meta property="og:description" content="' + html.escape(og_description, quote=True) + '">',
             '  <meta property="og:image" content="' + image + '">',
             '  <meta property="og:image:width" content="' + str(image_width) + '">',
             '  <meta property="og:image:height" content="' + str(image_height) + '">',
             '  <meta property="og:image:alt" content="' + html.escape(IMAGE_ALT, quote=True) + '">',
             '  <meta property="og:url" content="' + canonical + '">',
             '  <meta property="og:type" content="' + ("article" if kind == "guide" else "website") + '">',
             '  <meta property="og:locale" content="' + OG_LOCALE[locale] + '">',
             '  <meta name="twitter:card" content="summary_large_image">',
             '  <meta name="twitter:title" content="' + html.escape(title, quote=True) + '">',
             '  <meta name="twitter:description" content="' + html.escape(og_description, quote=True) + '">',
             '  <meta name="twitter:image" content="' + image + '">',
             '  <meta name="twitter:image:alt" content="' + html.escape(IMAGE_ALT, quote=True) + '">']
    block += ['  <link rel="alternate" hreflang="' + code + '" href="' + url(kind, code) + '">'
              for code in TRANSLATED[kind]]
    block.append('  <link rel="alternate" hreflang="x-default" href="' + url(kind, "en") + '">')
    block += ['  <script type="application/ld+json">' + json.dumps(json_ld, ensure_ascii=False, separators=(",", ":")) + '</script>']
    if locale != "en":
        existing = re.search(r'<meta name="source-sha256" content="([a-f0-9]{64})"\s*/?>', old)
        digest = source_hash(kind) if stamp or existing is None else existing.group(1)
        block.append('  <meta name="source-sha256" content="' + digest + '">')
    block.append("  <!-- /doc-quality metadata -->")
    # The block carries the one charset declaration, so it lands inside the first 1024 bytes.
    old = re.sub(r'\n[ \t]*<meta charset="[^"]*"\s*/?>', '', old, flags=re.I)
    if '<!-- doc-quality metadata:' in old:
        return re.sub(r'  <!-- doc-quality metadata:.*?<!-- /doc-quality metadata -->',
                      "\n".join(block), old, count=1, flags=re.S)
    # Remove the legacy head fields, preserving unrelated styling, scripts and icons.
    old = re.sub(r'\s*<title>.*?</title>', '', old, count=1, flags=re.S | re.I)
    old = re.sub(r'\s*<meta (?:name="(?:description|twitter:[^"]+|source-sha256)"|property="og:[^"]+")[^>]*>', '', old, flags=re.I)
    old = re.sub(r'\s*<link rel="(?:canonical|alternate)"[^>]*>', '', old, flags=re.I)
    old = re.sub(r'\s*<script type="application/ld\+json">.*?</script>', '', old, flags=re.S | re.I)
    return old.replace("<head>", "<head>\n" + "\n".join(block), 1)


def generated_files(write):
    pages = [(kind, locale, page(kind, locale)) for kind, locales in TRANSLATED.items()
             for locale in locales if page(kind, locale).exists()]
    dates, stale = lastmod_dates(pages, write)
    help_marker = BASE + "help/"
    sitemap_path = DOCS / "sitemap.xml"
    sitemap = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
    sitemap += "".join("  <url><loc>" + address + "</loc><lastmod>" + dates[address]["lastmod"] + "</lastmod></url>\n"
                       for address in sorted(dates))
    sitemap += "</urlset>\n"
    index_path = DOCS / "search-index.json"
    old_index = json.loads(index_path.read_text(encoding="utf-8-sig")) if index_path.exists() else []
    index = []
    for kind, locale, path in pages:
        text = path.read_text(encoding="utf-8")
        title = html.unescape(re.search(r"<title>(.*?)</title>", text, re.S | re.I).group(1))
        description = html.unescape(re.search(r'<meta name="description" content="([^"]*)"', text).group(1))
        headings = [html.unescape(re.sub(r"<[^>]+>", "", heading)).strip() for heading in
                    re.findall(r"<h[1-3]\b[^>]*>(.*?)</h[1-3]>", text, re.S | re.I)]
        index.append({"url": url(kind, locale), "lang": locale, "title": title,
                      "description": description, "headings": headings})
    index += [row for row in old_index if row.get("url", "").startswith(help_marker)]
    return ({sitemap_path: sitemap,
             index_path: json.dumps(index, ensure_ascii=False, indent=2) + "\n",
             LASTMOD: json.dumps(dates, ensure_ascii=False, indent=2, sort_keys=True) + "\n"}, stale)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--stamp-translations", action="store_true")
    args = parser.parse_args()
    if args.stamp_translations and not args.write:
        parser.error("--stamp-translations requires --write")
    failures = []
    facts = release_facts()
    for kind, locales in TRANSLATED.items():
        for locale in locales:
            path = page(kind, locale)
            if not path.exists():
                failures.append("missing " + str(path))
                continue
            actual = path.read_text(encoding="utf-8")
            expected = metadata(path, kind, locale, args.stamp_translations)
            if kind == "index":
                expected = with_release_block(expected, facts)
            if actual != expected:
                if args.write:
                    path.write_text(expected, encoding="utf-8", newline="\n")
                else:
                    failures.append("metadata drift: " + str(path.relative_to(ROOT)))
            if locale != "en" and source_hash(kind) not in expected:
                failures.append("stale translation: " + str(path.relative_to(ROOT)))
    files, stale = generated_files(args.write)
    failures += ["stale lastmod (content changed, run --write): " + address for address in stale]
    for path, expected in files.items():
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            if args.write:
                path.write_text(expected, encoding="utf-8", newline="\n")
            else:
                failures.append("generated file drift: " + str(path.relative_to(ROOT)))
    if failures:
        print("\n".join(failures))
        return 1
    print("documentation quality: PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
