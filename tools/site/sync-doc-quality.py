STORE_URL = "https://apps.microsoft.com/detail/9NB4W41NGQJ4"
RELEASES_URL = "https://github.com/SerZhyAle/CyrFlip/releases/latest"
RELEASE_BASE = "https://github.com/SerZhyAle/CyrFlip/releases"
LICENSE_URL = "https://github.com/SerZhyAle/CyrFlip/blob/main/LICENSE"
AUTHOR = {"@type": "Person", "name": "Serhii Zhyhunenko", "url": "https://github.com/SerZhyAle"}
SITE_ID = BASE + "#website"
SOCIAL_CARD = DOCS / "assets" / "social-card.png"
