IMAGE_ALT = "The CyrFlip icon and wordmark, with ghbdtn turning into привет"
LASTMOD = ROOT / "tools" / "site" / "sitemap-lastmod.json"
RELEASE_FACTS = ROOT / "tools" / "site" / "release-facts.json"
VERSION_SHAPE = re.compile(r"^\d{2}\.(?:[1-9]|1[0-2])\.(?:[1-9]|[12]\d|3[01])\.\d{4}$")
FACTS_OPEN = "<!-- release-facts: generated by tools/site/sync-doc-quality.py from tools/site/release-facts.json -->"
FACTS_CLOSE = "<!-- /release-facts -->"
FACTS_BLOCK = re.compile(re.escape(FACTS_OPEN) + r".*?" + re.escape(FACTS_CLOSE), re.S)
# The landing's settings capture of the conversion row; the locales without their own capture use the English one.
SCREENSHOT = "assets/guide-settings-3-{}.png"
