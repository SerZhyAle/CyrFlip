<#
    Render-CliDoc.ps1 - renders docs/CLI.md from docs/cli-commands.json (APP-COMMANDS rule 20, ticket S0107).

    docs/CLI.md is a render target: never edit it by hand, edit the manifest and run this script.
    With -Check it only compares and writes nothing - the fast tier (build.ps1 -Fast -Area cli) and the release
    preflight run it that way. Beyond the render it holds, statically and in well under a second:
      - the manifest's form (APP-COMMANDS rule 18: the members of every command, the closed vocabularies);
      - the static form of "the embedded resource is the file" (the project embeds docs\cli-commands.json under the
        name AppCommandManifest reads; the byte comparison itself is AppCommandsTests, release tier) and that the
        command code names every verb of the manifest;
      - the words that make the interface findable (ticket S0112): every risk class of the manifest on the 13 privacy
        pages and the 3 guides (canon invariant 14), the commands chapter in the guides, a link to it on the 13
        landings, and the one line in CLAUDE.md that tells a development agent where the list is.

    Exit codes: 0 the file matches (or was written); 1 a defect - docs/CLI.md differs from what the manifest renders,
    or one of the checks above failed (each is printed); 2 the manifest could not be read.
#>
[CmdletBinding()]
param([switch] $Check)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$manifestPath = Join-Path $repo 'docs\cli-commands.json'
$docPath = Join-Path $repo 'docs\CLI.md'

try { $m = Get-Content -LiteralPath $manifestPath -Raw -Encoding utf8 | ConvertFrom-Json }
catch { Write-Host "cli-doc: NOT VERIFIED (1) - cannot read docs/cli-commands.json: $($_.Exception.Message)"; exit 2 }

function Cell([string] $text) { return ($text -replace '\|', '\|') }

$out = [System.Collections.Generic.List[string]]::new()
$out.Add('# CyrFlip command line')
$out.Add('')
$out.Add('<!-- Generated by tools/cli/Render-CliDoc.ps1 from docs/cli-commands.json. Do not edit by hand. -->')
$out.Add('')
$out.Add("CyrFlip takes commands from scripts, shortcuts and other programs. A command is handled by the copy of CyrFlip that is already running; the process you start only carries it there, waits for the answer and exits with its code. Command set $($m.cliVersion), for ``$($m.exe)``. The same list is printed by ``$($m.exe) commands``, and ``$($m.exe) commands --json`` prints the manifest itself.")
$out.Add('')
$out.Add('CyrFlip.exe is a window program: a script that needs the exit code waits for it - `start /wait CyrFlip.exe status` in cmd, `(Start-Process .\CyrFlip.exe -ArgumentList ''status'' -Wait -PassThru).ExitCode` in PowerShell. `--result <path>` writes the answer''s data as one JSON file.')
$out.Add('')
$out.Add('Commands other than the safe ones run only while "Let other programs ask CyrFlip to work with my files, screen, clipboard or the network" is on, on the General page of the settings. The spellings CyrFlip shipped before (`/clipboard-send`, `/clipboard-get`, `/launcher-run:{guid}`, `/launcher-settings`, `/exit`) keep working as before and depend only on their own feature being on.')
$out.Add('')
$out.Add('| Command | What it does | Risk | With CyrFlip not running |')
$out.Add('| --- | --- | --- | --- |')
foreach ($c in $m.commands) {
    $out.Add("| ``$($c.name)`` | $(Cell $c.summary) | $($c.risk) | $($c.coldStart) |")
}
$out.Add('')
$out.Add('## Exit codes')
$out.Add('')
$out.Add('| Code | Meaning |')
$out.Add('| --- | --- |')
$out.Add('| 0 | done, or accepted |')
$out.Add('| 1 | the command ran and the operation failed |')
$out.Add('| 2 | not proven: no answer in time, or the running copy is older and takes no commands |')
$out.Add('| 10 | usage: unknown command, unknown option, a bad value, a command that is too long |')
$out.Add('| 11 | not ready: not running, busy, the feature is off, or the thing named does not exist |')
$out.Add('| 12 | permission: the setting is off, or CyrFlip runs as administrator and the caller does not |')
foreach ($c in $m.commands) {
    $out.Add('')
    $out.Add("## $($c.name)")
    $out.Add('')
    $out.Add($c.summary)
    $out.Add('')
    $out.Add('```')
    $out.Add($c.synopsis)
    $out.Add('```')
    $out.Add('')
    $wait = if ($c.wait -eq 'accepted') { 'answers once the work has started' } else { 'answers when the work is done' }
    $out.Add("Risk: ``$($c.risk)``. With CyrFlip not running: ``$($c.coldStart)``. Waits at most $($c.timeoutMs) ms; $wait.")
    $aliases = @($c.aliases | ForEach-Object { if ($_ -is [string]) { $_ } else { $_.spelling } } | Where-Object { $_ -ne '' })
    if ($aliases.Count -gt 0) {
        $out.Add('')
        $out.Add('Older spellings that still work: ' + (($aliases | ForEach-Object { "``$_``" }) -join ', ') + '.')
    }
    if (@($c.args).Count -gt 0) {
        $out.Add('')
        $out.Add('| Option | Kind | Meaning |')
        $out.Add('| --- | --- | --- |')
        foreach ($a in $c.args) {
            $kind = if ($a.kind -eq 'enum') { 'one of ' + (($a.values | ForEach-Object { "``$_``" }) -join ', ') } else { $a.kind }
            $out.Add("| ``--$($a.name)`` | $kind | $(Cell $a.description) |")
        }
    }
    if (@($c.returns).Count -gt 0) {
        $out.Add('')
        $out.Add('Data: ' + (($c.returns | ForEach-Object { "``$($_.name)`` ($($_.kind)) - $($_.description)" }) -join '; ') + '.')
    }
    $out.Add('')
    $out.Add('| Exit | Meaning |')
    $out.Add('| --- | --- |')
    foreach ($e in $c.exitCodes) { $out.Add("| $($e.code) | $(Cell $e.meaning) |") }
    foreach ($x in $c.examples) {
        $out.Add('')
        $out.Add("Example ($($x.shell)):")
        $out.Add('')
        $out.Add('```' + $(if ($x.shell -eq 'powershell') { 'powershell' } else { 'bat' }))
        $out.Add($x.line)
        $out.Add('```')
        $out.Add('')
        $out.Add("Expect: $($x.expect).")
    }
}
$text = ($out -join "`n") + "`n"

if ($Check) {
    $defects = [System.Collections.Generic.List[string]]::new()
    $current = if (Test-Path -LiteralPath $docPath) { [IO.File]::ReadAllText($docPath).Replace("`r`n", "`n") } else { '' }
    if ($current -ne $text) { $defects.Add('docs/CLI.md is not what docs/cli-commands.json renders. Run tools\cli\Render-CliDoc.ps1.') }

    # The manifest itself: the members APP-COMMANDS rule 18 asks of every command, and the closed vocabularies.
    $risks = @('safe', 'reads-user-data', 'writes-user-data', 'leaves-machine')
    $argKinds = @('string', 'path', 'int', 'bool', 'enum', 'guid')
    $required = @('name', 'aliases', 'summary', 'synopsis', 'args', 'returns', 'risk', 'coldStart', 'wait', 'timeoutMs',
                  'interactive', 'idempotent', 'exitCodes', 'examples', 'since')
    if ($m.schemaVersion -ne 1) { $defects.Add('manifest: schemaVersion is not 1.') }
    foreach ($member in 'product', 'exe', 'cliVersion') { if (-not $m.$member) { $defects.Add("manifest: no $member.") } }
    if ([string]$m.cliVersion -notmatch '^\d+\.\d+$') { $defects.Add('manifest: cliVersion is not MAJOR.MINOR.') }
    foreach ($dup in @($m.commands | Group-Object name | Where-Object Count -gt 1)) { $defects.Add("manifest: duplicate command $($dup.Name).") }
    foreach ($c in $m.commands) {
        $have = @($c.PSObject.Properties.Name)
        foreach ($member in $required) { if ($member -notin $have) { $defects.Add("manifest: $($c.name) has no $member.") } }
        if ($c.risk -notin $risks) { $defects.Add("manifest: $($c.name) has risk '$($c.risk)'.") }
        if ($c.coldStart -notin @('start', 'oneshot', 'refuse')) { $defects.Add("manifest: $($c.name) has coldStart '$($c.coldStart)'.") }
        if ($c.wait -notin @('accepted', 'done')) { $defects.Add("manifest: $($c.name) has wait '$($c.wait)'.") }
        if (-not ($c.timeoutMs -is [int] -or $c.timeoutMs -is [long]) -or $c.timeoutMs -lt 1) { $defects.Add("manifest: $($c.name) has no usable timeoutMs.") }
        if (@($c.exitCodes).Count -eq 0) { $defects.Add("manifest: $($c.name) lists no exit code.") }
        if (@($c.examples).Count -eq 0) { $defects.Add("manifest: $($c.name) has no example.") }
        foreach ($a in $c.args) {
            if ($a.kind -notin $argKinds) { $defects.Add("manifest: $($c.name) --$($a.name) has kind '$($a.kind)'.") }
            if ($a.kind -eq 'enum' -and @($a.values).Count -eq 0) { $defects.Add("manifest: $($c.name) --$($a.name) is an enum with no values.") }
        }
        foreach ($x in $c.examples) { if ($x.shell -notin @('cmd', 'powershell')) { $defects.Add("manifest: $($c.name) has an example for shell '$($x.shell)'.") } }
    }

    # The static form of "the embedded resource equals the file" (the byte test, AppCommandsTests, is release tier):
    # the project embeds that very file under the name the code reads, nothing else is embedded under it, and every
    # verb of the manifest is a literal the command code knows.
    $csproj = [IO.File]::ReadAllText((Join-Path $repo 'src\CyrFlip\CyrFlip.csproj'))
    $code = [IO.File]::ReadAllText((Join-Path $repo 'src\CyrFlip\AppCommandManifest.cs'))
    $logical = [regex]::Match($code, 'ResourceName\s*=\s*"([^"]+)"').Groups[1].Value
    $embeds = @([regex]::Matches($csproj, '<EmbeddedResource\s+Include="([^"]*cli-commands[^"]*)"\s+LogicalName="([^"]+)"'))
    if ($embeds.Count -ne 1) { $defects.Add("src\CyrFlip\CyrFlip.csproj embeds $($embeds.Count) command manifests, not exactly one.") }
    elseif ($embeds[0].Groups[1].Value -ne '..\..\docs\cli-commands.json') { $defects.Add("the project embeds '$($embeds[0].Groups[1].Value)', not docs\cli-commands.json.") }
    elseif ($embeds[0].Groups[2].Value -ne $logical -or -not $logical) { $defects.Add("the resource is embedded as '$($embeds[0].Groups[2].Value)' but AppCommandManifest.ResourceName is '$logical'.") }
    $commandCode = (Get-ChildItem -LiteralPath (Join-Path $repo 'src\CyrFlip') -Filter '*AppCommand*.cs' | ForEach-Object { [IO.File]::ReadAllText($_.FullName) }) -join "`n"
    foreach ($c in $m.commands) {
        if (-not $commandCode.Contains('"' + $c.name + '"')) { $defects.Add("the command code never names the verb '$($c.name)' that the manifest lists.") }
    }

    # The words that tell a person and an agent that the interface exists (ticket S0112): the privacy page and the
    # permission list name every risk class the manifest has verbs of (canon invariant 14), the guides carry the
    # chapter and the classes, every landing points at the chapter, and the agent-rules file has its one line.
    $classes = @($m.commands | ForEach-Object { $_.risk } | Sort-Object -Unique)
    $docs = Join-Path $repo 'docs'
    $locales = @('ru', 'uk', 'de', 'it', 'es', 'fr', 'pt', 'ar', 'hi', 'bn', 'ur', 'zh')
    $privacy = @('privacy.html') + @($locales | ForEach-Object { "$_/privacy.html" })
    $landing = @('index.html') + @($locales | ForEach-Object { "$_/index.html" })
    $guides = @('guide.html', 'ru/guide.html', 'uk/guide.html')
    foreach ($page in $privacy + $guides) {
        $html = [IO.File]::ReadAllText((Join-Path $docs $page))
        # A class stands in a <code> element (the Arabic and Urdu pages mark it dir="ltr").
        $missing = @($classes | Where-Object { $html -notmatch ('<code(?:\s[^>]*)?>' + [regex]::Escape($_) + '</code>') })
        if ($missing.Count -gt 0) { $defects.Add("docs/$page does not name the risk class(es) $($missing -join ', ').") }
    }
    foreach ($page in $guides) { if (-not ([IO.File]::ReadAllText((Join-Path $docs $page))).Contains('<section id="commands">')) { $defects.Add("docs/$page has no commands chapter.") } }
    foreach ($page in $landing) { if (([IO.File]::ReadAllText((Join-Path $docs $page))) -notmatch 'href="(\.\./)?guide\.html#commands"') { $defects.Add("docs/$page does not point at the commands chapter.") } }
    $agentLine = @([IO.File]::ReadAllLines((Join-Path $repo 'CLAUDE.md')) | Where-Object { $_.Contains('docs/CLI.md') -and $_.Contains('commands --json') })
    if ($agentLine.Count -eq 0) { $defects.Add('CLAUDE.md has no line that names docs/CLI.md and commands --json for a development agent.') }

    if ($defects.Count -gt 0) {
        foreach ($d in $defects) { Write-Host "cli-doc: $d" }
        Write-Host "cli-doc: FAIL ($($defects.Count))"
        exit 1
    }
    Write-Host 'cli-doc: PASS'
    exit 0
}
[IO.File]::WriteAllText($docPath, $text, [Text.UTF8Encoding]::new($false))
Write-Host 'cli-doc: PASS (written)'
exit 0
