using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;

namespace IconGen
{
    /// <summary>
    /// The <c>symbols</c> verb (ticket S0056): generates <c>src/CyrFlip/Symbols.g.cs</c> from the curated
    /// <c>tools/symbols/symbols.src</c> source file and the Unicode Character Database's <c>UnicodeData.txt</c>
    /// (the UCD path is an argument, never a literal).
    ///
    /// If any code point is missing from UnicodeData.txt, the run fails and leaves the existing file untouched.
    /// </summary>
    internal static class SymbolVendoring
    {
        public static int Run(string root, string[] args)
        {
            string? ucdPath = ArgValue(args, "-UcdPath") ?? ArgValue(args, "-Ucd");
            if (string.IsNullOrWhiteSpace(ucdPath))
                return Fail("Usage: symbols -UcdPath <UnicodeData.txt> [-Src <symbols.src>] [-Out <Symbols.g.cs>]");

            if (!File.Exists(ucdPath))
                return Fail("UnicodeData.txt not found: " + ucdPath);

            string srcPath = ArgValue(args, "-Src") ?? Path.Combine(root, "tools", "symbols", "symbols.src");
            if (!File.Exists(srcPath))
                return Fail("Source file not found: " + srcPath);

            string outPath = ArgValue(args, "-Out") ?? Path.Combine(root, "src", "CyrFlip", "Symbols.g.cs");

            // 1. Read UCD
            var ucd = new Dictionary<int, string>();
            foreach (string line in File.ReadLines(ucdPath, Encoding.UTF8))
            {
                if (string.IsNullOrWhiteSpace(line)) continue;
                int semi = line.IndexOf(';');
                if (semi <= 0) continue;
                string hex = line.Substring(0, semi);
                if (!int.TryParse(hex, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out int cp))
                    continue;
                int secondSemi = line.IndexOf(';', semi + 1);
                string name = secondSemi > semi ? line.Substring(semi + 1, secondSemi - semi - 1) : line.Substring(semi + 1);
                ucd[cp] = name;
            }

            // 2. Read symbols.src
            var entries = new List<(string Hex, int CodePoint, string Category, string NameRu, string Keywords, string? Label)>();
            var seen = new HashSet<int>();
            int lineNum = 0;
            foreach (string rawLine in File.ReadLines(srcPath, Encoding.UTF8))
            {
                lineNum++;
                string line = rawLine.Trim();
                if (line.Length == 0 || line.StartsWith("#", StringComparison.Ordinal)) continue;

                string[] parts = line.Split(';');
                if (parts.Length < 3)
                    return Fail($"symbols.src line {lineNum}: expected at least HEX;category;nameRu but got: {line}");

                string hex = parts[0].Trim();
                if (!int.TryParse(hex, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out int cp))
                    return Fail($"symbols.src line {lineNum}: invalid hex '{hex}'");

                if (seen.Contains(cp))
                    return Fail($"symbols.src line {lineNum}: duplicate code point U+{cp:X4}");
                seen.Add(cp);

                if (!ucd.TryGetValue(cp, out string? nameEn) || string.IsNullOrWhiteSpace(nameEn))
                    return Fail($"symbols.src line {lineNum}: code point U+{cp:X4} is missing from UnicodeData.txt");

                string category = parts[1].Trim();
                string nameRu = parts[2].Trim();
                string keywords = parts.Length > 3 ? parts[3].Trim() : string.Empty;
                string? label = parts.Length > 4 && parts[4].Trim().Length > 0 ? parts[4].Trim() : null;

                entries.Add((hex, cp, category, nameRu, keywords, label));
            }

            if (entries.Count == 0)
                return Fail("No entries found in " + srcPath);

            // 3. Generate Symbols.g.cs
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append("// Generated by tools/IconGen (symbols verb) from tools/symbols/symbols.src and UnicodeData.txt.\n");
            sb.Append("// Never edit by hand: change tools/symbols/symbols.src and run\n");
            sb.Append("//   dotnet run --project tools/IconGen -- symbols -UcdPath <path-to-UnicodeData.txt>\n");
            sb.Append("// </auto-generated>\n");
            sb.Append("using System;\n\n");
            sb.Append("namespace CyrFlip\n{\n");
            sb.Append("    internal static partial class SymbolsData\n    {\n");
            sb.Append("        internal static readonly SymbolEntry[] Table =\n        {\n");

            foreach (var e in entries)
            {
                string textLiteral = EscapeCharLiteral(e.CodePoint);
                string nameEn = EscapeString(ucd[e.CodePoint]);
                string nameRu = EscapeString(e.NameRu);
                string keywords = EscapeString(e.Keywords);
                string labelLiteral = e.Label != null ? $"\"{EscapeString(e.Label)}\"" : "null";
                bool isCombining = string.Equals(e.Category, "combining", StringComparison.OrdinalIgnoreCase);

                sb.Append("            new SymbolEntry(\n");
                sb.Append($"                text: \"{textLiteral}\",\n");
                sb.Append($"                codePoint: 0x{e.CodePoint:X4},\n");
                sb.Append($"                category: \"{e.Category}\",\n");
                sb.Append($"                nameEn: \"{nameEn}\",\n");
                sb.Append($"                nameRu: \"{nameRu}\",\n");
                sb.Append($"                keywords: \"{keywords}\",\n");
                sb.Append($"                label: {labelLiteral},\n");
                sb.Append($"                isCombining: {(isCombining ? "true" : "false")}),\n");
            }

            sb.Append("        };\n");
            sb.Append("    }\n");
            sb.Append("}\n");

            Directory.CreateDirectory(Path.GetDirectoryName(outPath)!);
            File.WriteAllText(outPath, sb.ToString(), Encoding.UTF8);
            Console.WriteLine($"Successfully generated {entries.Count} symbols in {outPath}");
            return 0;
        }

        private static string EscapeCharLiteral(int codePoint)
        {
            if (codePoint <= 0xFFFF)
                return $"\\u{codePoint:X4}";
            string utf32 = char.ConvertFromUtf32(codePoint);
            return $"\\u{(int)utf32[0]:X4}\\u{(int)utf32[1]:X4}";
        }

        private static string EscapeString(string value) =>
            value.Replace("\\", "\\\\").Replace("\"", "\\\"");

        private static string? ArgValue(string[] args, string flag)
        {
            for (int i = 0; i < args.Length - 1; i++)
            {
                if (string.Equals(args[i], flag, StringComparison.OrdinalIgnoreCase))
                    return args[i + 1];
            }
            return null;
        }

        private static int Fail(string message)
        {
            Console.Error.WriteLine(message);
            return 1;
        }
    }
}
